#!/usr/bin/env python3
"""Every call a lifted battle body makes must be one the port can dispatch.

A lifted port body (include/battle_lift.h, tools/scripts/battle_lift_asm.py)
reaches its callees the way an interpreted `jal` does: through
PcPort_BattleMipsCallJal / bl_call_guest (runtime_bridge: native binding if
the bridge has one, else the interpreter) or, for the bridge-contract
wrappers, as a direct C call.  An overlay callee can always fall back to the
interpreter (its retail bytes are resident).  A MAIN-EXECUTABLE callee
cannot: the main executable's .text is not in guest RAM, so it must have a
native binding, exactly as runtime_bridge_call makes it:

  * the bridge map (battle_bridge_map.inc, gen_battle_bridge_map.py) lists a
    function symbol at that address;
  * the port binary exports that name (dlsym(RTLD_DEFAULT) binds it), or the
    runtime's own special case binds it (0x8003F8B0/0x8003F8CC -> rsin/rcos),
    or it is one of the C library names the bridge binds through dlsym and
    runs over the resolved guest range (bzero, memmove, memcpy in
    bridge_module_memory; memset in bridge_target_camera_graphics) and the
    C library resolves it;
  * it is not a generated stub (stubs.c: xeno_port_is_generated_stub).

Each lifted body's calls are read from the lifter's per-instruction comments
(`/* ADDR jal NAME */`, one per retail jal), so a body generated by any lifter
mode is covered.  Exit 1 and one line per undispatchable target.

    check_battle_lift_jal_targets.py [--binary pc_port/build_native/xeno-port]
        [--map pc_port/build_native/battle_bridge_map.inc]
        [--stubs pc_port/build_native/stubs.c]
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OVERLAY_LO = 0x8006FAF0
JAL_RE = re.compile(r"/\* ([0-9A-F]{8}) jal (\w+) \*/")
FUNC_RE = re.compile(r"^\w[\w\s\*]*\b(func_[0-9A-Fa-f]{8})\s*\([^;]*\)\s*\{", re.M)
MAP_RE = re.compile(r"\{\s*0x([0-9a-fA-F]+)u,\s*\d+u,\s*(\d),\s*\"(\w+)\"\s*\}")
# runtime_bridge_call / initialize_runtime special cases.
SPECIAL = {0x8003F8B0: "rsin", 0x8003F8CC: "rcos"}
# Names the bridge binds from the C library through dlsym(RTLD_DEFAULT)
# (bridge_module_memory runs bzero/memmove/memcpy, and
# bridge_target_camera_graphics runs memset, over the resolved guest range):
# the port binary does not export them, the C library in its process does.
LIBC_BOUND = ("bzero", "memmove", "memcpy", "memset")


def libc_resolves(name: str) -> bool:
    import ctypes
    import ctypes.util

    path = ctypes.util.find_library("c")
    if path is None:
        return False
    try:
        return hasattr(ctypes.CDLL(path), name)
    except OSError:
        return False


def symbols() -> dict[str, int]:
    out: dict[str, int] = {}
    for rel in ("config/symbol_addrs.slus_006.64.txt",
                "linker/undefined_funcs_auto.battle.txt",
                "config/symbol_addrs.battle.txt"):
        path = ROOT / rel
        if not path.exists():
            continue
        for line in path.read_text().splitlines():
            m = re.match(r"^\s*(\w+)\s*=\s*(0x[0-9A-Fa-f]+)", line)
            if m:
                out.setdefault(m.group(1), int(m.group(2), 16))
    return out


def lifted_calls() -> dict[str, list[tuple[int, str]]]:
    """lifted function -> [(jal site, callee name)]"""
    out: dict[str, list[tuple[int, str]]] = {}
    paths = sorted((ROOT / "src" / "battle").glob("*.c"))
    paths.append(ROOT / "pc_port/src/battle_module_0c4_lift_host.inc")
    for path in paths:
        text = path.read_text(errors="ignore")
        if '#include "battle_lift.h"' not in text:
            continue
        starts = [(m.start(), m.group(1)) for m in FUNC_RE.finditer(text)]
        for m in JAL_RE.finditer(text):
            owner = None
            for pos, name in starts:
                if pos < m.start():
                    owner = name
            if owner is None:
                continue
            body_head = text[[p for p, n in starts if n == owner][-1]:m.start()]
            if "static const char FN[]" not in body_head:
                continue  # not a lifted body
            out.setdefault(owner, []).append((int(m.group(1), 16), m.group(2)))
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--binary", default=str(ROOT / "pc_port/build_native/xeno-port"))
    ap.add_argument("--map", default=str(ROOT / "pc_port/build_native/battle_bridge_map.inc"))
    ap.add_argument("--stubs", default=str(ROOT / "pc_port/build_native/stubs.c"))
    a = ap.parse_args()

    syms = symbols()
    bridge: dict[int, str] = {}
    for m in MAP_RE.finditer(Path(a.map).read_text()):
        if m.group(2) == "1":
            bridge.setdefault(int(m.group(1), 16), m.group(3))
    stubs_text = Path(a.stubs).read_text()
    stubs = set(re.findall(r"^long\s+(\w+)\(void\)\s*\{", stubs_text, re.M))
    nm = subprocess.run(["nm", "-D", "--defined-only", a.binary],
                        capture_output=True, text=True, check=True).stdout
    exported = {line.split()[-1] for line in nm.splitlines() if line.split()}

    bad = 0
    calls = lifted_calls()
    total = 0
    main_exe: set[str] = set()
    for owner, sites in sorted(calls.items()):
        for site, name in sites:
            total += 1
            m = re.fullmatch(r"func_([0-9A-Fa-f]{8})", name)
            addr = int(m.group(1), 16) if m else syms.get(name)
            if addr is None:
                print(f"LIFT JAL {owner} @{site:08X}: callee {name} has no address")
                bad += 1
                continue
            if addr >= OVERLAY_LO:
                continue  # resident retail bytes: native if adopted, else interpreted
            main_exe.add(name)
            bound = SPECIAL.get(addr) or bridge.get(addr)
            if bound is None:
                print(f"LIFT JAL {owner} @{site:08X}: main-exe {name} 0x{addr:08X} "
                      f"is not in the bridge map")
                bad += 1
            elif bound not in exported and not (bound in LIBC_BOUND and libc_resolves(bound)):
                print(f"LIFT JAL {owner} @{site:08X}: main-exe {name} 0x{addr:08X} "
                      f"({bound}) is not exported by {a.binary}")
                bad += 1
            elif bound in stubs:
                print(f"LIFT JAL {owner} @{site:08X}: main-exe {name} 0x{addr:08X} "
                      f"({bound}) is a generated stub")
                bad += 1
    print(f"# lifted bodies {len(calls)}, jal sites {total}, main-exe callees "
          f"{len(main_exe)}: {' '.join(sorted(main_exe))}", file=sys.stderr)
    if bad:
        print(f"ERROR: {bad} lifted jal target(s) the port cannot dispatch", file=sys.stderr)
        return 1
    print("# every lifted jal target is dispatchable (overlay: native or interpreted; "
          "main-exe: bound native, exported, not a stub)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())

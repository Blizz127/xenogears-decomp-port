#!/usr/bin/env python3
"""gen_dev_menu_tables.py SPOTS.json RESULTS.json [--evidence-root PATH] -- emit the
dev-menu warp / step tables from VERIFIED sweep results only.

SPOTS.json  (hand-written metadata; names are our own words)
  {"warps": [{"id","disc","chapter","area","spot","map","entrance","scenario"|null}],
   "steps": [{"id","disc","chapter","area","name","detect_scen","detect_map"|null,
              "detect_var":[addr,value]|null,"writes":[[addr,value],...],
              "next_map","next_entrance","area_last"}],
   "references": "walkthrough references"}
RESULTS.json  output of pc_port/tests/warp_sweep_analyze.py --json (verified flag per id)

Writes pc_port/src/port_dev_menu_warps.c and port_dev_menu_steps.c.  A row is
emitted only when RESULTS marks its id verified, so an unverified target can
never reach the menu; the evidence string is the target's sweep directory name.
"""
import json, os, sys

args = [a for a in sys.argv[1:] if not a.startswith('--')]
spots = json.load(open(args[0]))
res = json.load(open(args[1]))
ev_root = sys.argv[sys.argv.index('--evidence-root') + 1] if '--evidence-root' in sys.argv else ''
ok = {r['id']: r for r in res['results'] if r['verified']}
root = os.path.join(os.path.dirname(__file__), '..', '..', 'pc_port', 'src')


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def evidence(i):
    return cstr(os.path.join(ev_root, i) if ev_root else i)


warps = [w for w in spots['warps'] if w['id'] in ok]
steps = [s for s in spots['steps'] if s['id'] in ok]

out = ['''/* Verified dev-menu warp table (DEV_MENU_SPEC.md 6).  GENERATED by
 * tools/analysis/gen_dev_menu_tables.py from warp sweep results: a row exists
 * only when pc_port/tests/warp_sweep_analyze.py reported it VERIFIED (arrival,
 * idle, walk-in from a fresh post-battle checkpoint).  Names are our own words;
 * ordering/names follow the public walkthrough references.
 *
 *   { disc, chapter, area, spot, map, entrance, progression (scenario word), evidence }
 */
#include <stddef.h>
#include "port_dev_menu.h"

const PcPortDevWarp g_PcPortDevWarps[] = {''']
for w in warps:
    scen = 'PC_DEV_NO_SCENARIO' if w.get('scenario') in (None, -1) else '%du' % w['scenario']
    out.append('    { %d, %s, %s, %s, %d, %d, %s, %s },' % (
        w['disc'], cstr(w['chapter']), cstr(w['area']), cstr(w['spot']), w['map'], w['entrance'], scen, evidence(w['id'])))
out.append('    { 0, NULL, "", "", -1, 0, 0u, NULL } /* sentinel */')
out.append('};')
out.append('const int g_PcPortDevWarpCount = %d;' % len(warps))
out.append('')
areas = []
for s in steps:
    if s.get('area_last') and s['area'] not in [a[0] for a in areas]:
        areas.append((s['area'], s['disc'], s['chapter'], s['id']))
out.append('const PcPortDevFinish g_PcPortDevFinishes[] = {')
for a, d, c, i in areas:
    out.append('    { %d, %s, %s, %s },' % (d, cstr(c), cstr(a), evidence(i)))
out.append('    { 0, NULL, "", NULL } /* sentinel */')
out.append('};')
out.append('const int g_PcPortDevFinishCount = %d;' % len(areas))
open(os.path.join(root, 'port_dev_menu_warps.c'), 'w').write('\n'.join(out) + '\n')

so = ['''/* Verified Finish Current Step table (DEV_MENU_SPEC.md 7a).  GENERATED by
 * tools/analysis/gen_dev_menu_tables.py.  Each step's `writes` are script-variable
 * values observed in the recorded real route (XENO_ROUTE_LOG, analyzed by
 * tools/analysis/route_steps.py); a row exists only when the sweep verified
 * arrival, idle and the next trigger.  Step names are our own words; ordering
 * follows the public walkthrough references (no guide text is copied). */
#include <stddef.h>
#include "port_dev_menu.h"
''']
for s in steps:
    if s['writes']:
        so.append('static const PcPortDevStepWrite k_%s_w[] = { %s };' % (
            s['id'], ', '.join('{ 0x%x, %d }' % (a, v) for a, v in s['writes'])))
so.append('')
so.append('const PcPortDevStep g_PcPortDevSteps[] = {')
for s in steps:
    dv = s.get('detect_var') or [None, None]
    so.append('    { %s, %d, %s, %s, %s, %d, %d, %s, %s, %s, %d, %d, %d, %d, %s },' % (
        cstr(s['id']), s['disc'], cstr(s['chapter']), cstr(s['area']), cstr(s['name']), s['detect_scen'],
        -1 if s.get('detect_map') is None else s['detect_map'],
        'PC_DEV_NO_VALUE' if dv[0] is None else '0x%x' % dv[0], '0' if dv[1] is None else str(dv[1]),
        ('k_%s_w' % s['id']) if s['writes'] else 'NULL', len(s['writes']), s['next_map'], s['next_entrance'],
        1 if s.get('area_last') else 0, evidence(s['id'])))
so.append('    { NULL, 0, NULL, "", "", 0, -1, PC_DEV_NO_VALUE, 0, NULL, 0, -1, 0, 0, NULL } /* sentinel */')
so.append('};')
so.append('const int g_PcPortDevStepCount = %d;' % len(steps))
open(os.path.join(root, 'port_dev_menu_steps.c'), 'w').write('\n'.join(so) + '\n')
print('warps: %d/%d verified rows emitted, steps: %d/%d' % (len(warps), len(spots['warps']), len(steps), len(spots['steps'])))

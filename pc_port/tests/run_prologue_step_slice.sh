# XENO_BATTLE_NATIVE_ACTOR_CREATE, XENO_BATTLE_NATIVE_RESOURCE_INIT, XENO_BATTLE_NATIVE_TRANSITION, XENO_BATTLE_NATIVE_SHARD_SETUP,
# XENO_BATTLE_NATIVE_MODULE_SETUP, XENO_BATTLE_NATIVE_MODULE_STAGE1,
# XENO_BATTLE_NATIVE_MODULE_STAGE2, XENO_BATTLE_NATIVE_MODULE_STAGE3, XENO_BATTLE_NATIVE_EFFECT_RESET, XENO_BATTLE_NATIVE_TEXT_ALLOCATION, XENO_BATTLE_NATIVE_GLYPHS, XENO_BATTLE_NATIVE_TURN_SPEED,
# XENO_BATTLE_NATIVE_TARGET_LIST, XENO_BATTLE_NATIVE_TEXTURE,
# XENO_BATTLE_NATIVE_SHARD_CALLBACKS, XENO_BATTLE_NATIVE_PARTY_STATS, XENO_BATTLE_NATIVE_LEAVES,
# XENO_BATTLE_EXIT_HASH, XENO_CPU_FALLBACK_TOP,
# XENO_BATTLE_TEST_PAD, XENO_BATTLE_STATE_HASH_LOG. The battle identity leg
# continues the route past map 2 through the opening battle with them.
set -u
BINARY=$1; OUT=$2; MODE=$3

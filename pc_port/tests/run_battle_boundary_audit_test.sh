#!/usr/bin/env bash
# Native-only boundary audit (test only): the main-executable targets F1
# (07901ea0) binds to legacy native C when a caller-host hook declines, run
# as retail SLUS_006.64 bytes in the interpreter against the legacy body on
# the production bridge path.  See pc_port/tests/battle_boundary_audit_test.c.
#
# Requires a port build (pc_port/build_native: stubs.c and the production
# objects of the audited bodies, linked unmodified) and the matching build's
# symbol files (the bridge map).  Output goes to BATTLE_BOUNDARY_AUDIT_OUT,
# which must be set (a scratch directory, never /tmp).
#
# usage: run_battle_boundary_audit_test.sh [target-name ...]
set -euo pipefail
ulimit -c 0
cd "$(dirname "$0")/../.."
OUT=${BATTLE_BOUNDARY_AUDIT_OUT:?set BATTLE_BOUNDARY_AUDIT_OUT to a scratch directory}
EXE=${BATTLE_BOUNDARY_AUDIT_EXE:-disc/SLUS_006.64}
OBJ=pc_port/build_native/obj
mkdir -p "$OUT"
for f in pc_port/build_native/stubs.c "$EXE"; do
    [ -f "$f" ] || { echo "AUDIT FAIL missing $f (build the port first)" >&2; exit 1; }
done

bridge_elf=()
[ -f build/out/slus_006.64.elf ] && bridge_elf+=(--elf build/out/slus_006.64.elf)
python3 tools/scripts/gen_battle_bridge_map.py "${bridge_elf[@]}" \
    --symbols config/symbol_addrs.slus_006.64.txt \
    --symbols linker/undefined_funcs_auto.battle.txt \
    --symbols linker/undefined_syms_auto.battle.txt \
    --symbols config/symbol_addrs.battle.txt \
    --out "$OUT/battle_bridge_map.inc"

COMMON=(-std=gnu17 -fno-pie -DXENO_PC_PORT -DSKIP_ASM -D_LANGUAGE_C
    -DUSE_EXTENDED_PRIM_POINTERS=0 -include assert.h -ffunction-sections -fdata-sections
    -Ipc_port/include_shim -Iinclude -Ipc_port/src -I"$OUT"
    -Ipc_port/extern/PsyCross/include -Ipc_port/extern/PsyCross/include/psx)

# _GNU_SOURCE (empty, as the runtime source defines it) for dladdr and
# REG_RIP; -include assert.h reads the feature macros before the file does.
# BATTLE_BOUNDARY_AUDIT_RUNTIME: another copy of battle_mips_runtime.c (a
# mutant run: quoted includes resolve next to it first, then pc_port/src).
RUNTIME_SRC=${BATTLE_BOUNDARY_AUDIT_RUNTIME:-$PWD/pc_port/src/battle_mips_runtime.c}
clang "${COMMON[@]}" -D_GNU_SOURCE= -O0 -g -Wall -Wextra -Werror \
    -DBATTLE_RUNTIME_SOURCE="\"$RUNTIME_SRC\"" \
    -c pc_port/tests/battle_boundary_audit_test.c -o "$OUT/test.o"
clang "${COMMON[@]}" -O0 -g -c pc_port/src/battle_mips_adapter.c -o "$OUT/cpu.o"
gcc -c pc_port/build_native/stubs.c -O0 -g -o "$OUT/stubs.o"

# The audited bodies and the main-executable services they reach, as the
# port links them (unmodified production objects).  A mutant run replaces
# one of them with BATTLE_BOUNDARY_AUDIT_OBJ_<name>=<object>.
OBJS=()
for name in src_slus_006.64_system_animation_scripts.c.o \
            src_slus_006.64_system_graphics.c.o \
            src_slus_006.64_system_temp2.c.o \
            world_map_helper_3101c.c.o \
            src_slus_006.64_system_memory.c.o \
            src_slus_006.64_system_system.c.o \
            src_slus_006.64_system_temp1.c.o \
            src_slus_006.64_system_temp3.c.o \
            model_prim_link.c.o \
            guest_prim_link.c.o; do
    var="BATTLE_BOUNDARY_AUDIT_OBJ_${name//[^A-Za-z0-9_]/_}"
    obj="${!var:-$OBJ/$name}"
    [ -f "$obj" ] || { echo "AUDIT FAIL missing $obj (build the port first)" >&2; exit 1; }
    OBJS+=("$obj")
done
# PsyCross GTE (the interpreter's COP2 and the native libgte calls share it).
for gte_src in psx/INLINE_C.C gte/PsyX_GTE.cpp; do
    g++ -std=c++17 -fno-pie -O0 -fpermissive -w -DUSE_EXTENDED_PRIM_POINTERS=0 \
        -Ipc_port/extern/PsyCross/include -Ipc_port/extern/PsyCross/include/psx \
        -include pc_port/src/port_compat.h \
        -c "pc_port/extern/PsyCross/src/$gte_src" -o "$OUT/gte_${gte_src##*/}.o"
done
PSYLIB=$(find pc_port/build -name libpsycross.a 2>/dev/null | head -1)
[ -n "$PSYLIB" ] || { echo "AUDIT FAIL missing libpsycross.a" >&2; exit 1; }
mkdir -p "$OUT/psycross"
PSYLIB_ABS="$PWD/$PSYLIB"
(cd "$OUT/psycross" && ar x "$PSYLIB_ABS" LIBGTE.C.o)
OBJS+=("$OUT/gte_INLINE_C.C.o" "$OUT/gte_PsyX_GTE.cpp.o" "$OUT/psycross/LIBGTE.C.o")

LINK=("$OUT/test.o" "$OUT/cpu.o" "${OBJS[@]}" "$OUT/stubs.o")
extra=()
if ! clang -no-pie -rdynamic -O0 -Wl,--gc-sections -Wl,--no-demangle "${LINK[@]}" \
        -ldl -lstdc++ -lm -o "$OUT/audit" 2>"$OUT/link.err"; then
    missing=$(grep -oE "undefined reference to \`[A-Za-z0-9_]+'" "$OUT/link.err" \
        | sed "s/.*\`//; s/'//" | sort -u)
    if [ -z "$missing" ]; then
        cat "$OUT/link.err" >&2
        echo "AUDIT FAIL link failed (no undefined references)" >&2
        exit 1
    fi
    {
        echo '/* Generated by run_battle_boundary_audit_test.sh: placeholders for'
        echo ' * callees and data this link lacks.  A case reaching a placeholder'
        echo ' * function is inconclusive (g_prover_placeholder_hits). */'
        echo '#include <stdio.h>'
        echo 'extern unsigned g_prover_placeholder_hits;'
        echo 'static void unresolved(const char *name) {'
        echo '    static const char *seen[256]; static int count; int i;'
        echo '    g_prover_placeholder_hits++;'
        echo '    for (i = 0; i < count; i++) if (seen[i] == name) return;'
        echo '    if (count < 256) seen[count++] = name;'
        echo '    fprintf(stderr, "[audit] unavailable callee %s (case inconclusive)\n", name);'
        echo '}'
        for sym in $missing; do
            case "$sym" in
                D_*|g_*|jtbl_*|jpt_*|str_*|aD_*|aG_*|gteRegs|activeDispEnv|activeDrawEnv|currentDispEnv)
                    echo "unsigned char $sym[0x10000];" ;;
                *)
                    echo "void $sym(void) { unresolved(\"$sym\"); }" ;;
            esac
        done
    } > "$OUT/placeholders.c"
    clang -c "$OUT/placeholders.c" -O0 -o "$OUT/placeholders.o"
    extra=("$OUT/placeholders.o")
    echo "AUDIT placeholders=$(echo "$missing" | wc -l)"
    clang -no-pie -rdynamic -O0 -Wl,--gc-sections "${LINK[@]}" "${extra[@]}" \
        -ldl -lstdc++ -lm -o "$OUT/audit"
fi
"$OUT/audit" "$EXE" "$@"
